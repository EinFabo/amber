"""Prints a stand-in for the R class AAPT2 generates, for tools/typecheck-android.sh.

Usage: python3 -I tools/gen_r_stub.py app/src/main/res > GeneratedR.kt

Strings and plurals from values/*.xml, drawables by file name. The ids are all 0: the type
check only needs the names to exist (tools/check_refs.py proves they are real resources).
"""
import pathlib
import re
import sys

res = pathlib.Path(sys.argv[1])
kinds = {"string": set(), "plurals": set(), "drawable": set()}
for f in (res / "values").glob("*.xml"):
    text = f.read_text(encoding="utf-8")
    for kind, name in re.findall(r'<(string|plurals)\s+name="([^"]+)"', text):
        kinds[kind].add(name)
for d in res.glob("drawable*"):
    for f in d.iterdir():
        kinds["drawable"].add(f.name.split(".")[0])

print("// Generated by tools/gen_r_stub.py from app/src/main/res - do not edit.")
print("package app.amethyst")
print()
print("object R {")
for kind in ("string", "plurals", "drawable"):
    print(f"    object {kind} {{")
    for name in sorted(kinds[kind]):
        print(f"        const val {name} = 0")
    print("    }")
print("}")
